package frgp.utn.edu.app_padresprimerizos;

public class Vacuna {

    private int idVacuna = 0;
    private String nombre = "";
    private int edadAplicacion = 0;

    public int getIdVacuna() { return idVacuna; }
    public void setIdVacuna(int idVacuna) { this.idVacuna = idVacuna; }

    public String getNombre() { return nombre; }
    public void setNombre(String nombre) { this.nombre = nombre; }

    public int getEdadAplicacion() { return edadAplicacion; }
    public void setEdadAplicacion(int edadAplicacion) { this.edadAplicacion = edadAplicacion; }
}
